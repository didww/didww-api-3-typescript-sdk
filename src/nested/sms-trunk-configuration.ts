import { camel } from 'kitsu-core';
import type { SmsBodyType, SmsHttpMethod, SmsServerLocation } from '../enums.js';
import { DidwwClientError } from '../errors.js';
import { cloneJson, isPlainObject, normalizeNumbers } from '../json.js';
import { redactSensitiveKeys } from '../redact.js';

/** Delivers inbound messages by email. `sendTo`, `subject` and `message` are required on create. */
export interface SmsToEmailConfiguration {
  type: 'sms_to_email';
  sendTo?: string;
  subject?: string;
  message?: string;
}

/**
 * Delivers inbound messages to an HTTP endpoint.
 *
 * `url` and `httpMethod` are required on create; `bodyType` and `body` are
 * required when `httpMethod` is POST or PUT and refused when it is GET.
 * `body` is a JSON string for `SmsBodyType.JSON`, an object of form fields for
 * the form encodings and a string for `SmsBodyType.RAW`. The keys of
 * `queryParameters`, `headers` and a form `body` are sent exactly as given.
 * `headers` is masked by `util.inspect` and `JSON.stringify`.
 */
export interface SmsHttpInConfiguration {
  type: 'http_in';
  url?: string;
  httpMethod?: SmsHttpMethod;
  queryParameters?: Record<string, string> | null;
  headers?: Record<string, string> | null;
  bodyType?: SmsBodyType | null;
  body?: string | Record<string, string> | null;
  followRedirect?: boolean;
  validateHttpsCertificate?: boolean;
}

/** Accepts outbound messages over HTTP. The credentials are generated by the API. */
export interface SmsHttpOutConfiguration {
  type: 'http_out';
  callbackUrl?: string | null;
  allowedIps?: string[] | null;
  /** **Read-only:** generated by the API, never sent. */
  authName?: string | null;
  /** **Read-only:** generated by the API, never sent. */
  authPassword?: string | null;
}

/**
 * Accepts an SMPP bind from your ESME. `serverLocation` is required on create;
 * the credentials are generated by the API.
 */
export interface SmsSmppEsmeConfiguration {
  type: 'smpp_esme';
  systemType?: string | null;
  allowedIps?: string[] | null;
  serverLocation?: SmsServerLocation;
  /** **Read-only:** generated by the API, never sent. */
  systemId?: string;
  /** **Read-only:** generated by the API, never sent. */
  password?: string;
}

/**
 * DIDWW binds to your SMSC. `host`, `systemId` (up to 15 characters),
 * `password` (up to 8 characters) and `serverLocation` are required on create;
 * `txPort` and `rxPort` default to 2775 and 2776.
 */
export interface SmsSmppSmscConfiguration {
  type: 'smpp_smsc';
  host?: string;
  txPort?: number;
  rxPort?: number;
  transceiverMode?: boolean;
  connectionTimeout?: number;
  useSsl?: boolean;
  systemId?: string;
  systemType?: string | null;
  password?: string;
  serverLocation?: SmsServerLocation;
}

/**
 * A configuration of a type this SDK version does not know, or one you want
 * to send exactly as written. `attributes` holds the wire attributes: keys are
 * never renamed, numbers keep their exact text ({@link JsonNumber}) and every
 * value, nulls included, is sent as is. Read-only attributes are not stripped.
 */
export interface GenericSmsTrunkConfiguration {
  type: string;
  attributes: Record<string, unknown>;
}

/**
 * Configuration of an SMS trunk.
 *
 * A generic configuration is told apart by its `attributes` key, not by its
 * `type` (it may carry a known type name), so `switch (config.type)` does not
 * narrow the union: use the `isSms*` guards.
 *
 * On update the `type` must match the trunk's, and attributes left out keep
 * their stored values. Typed configurations send every writable attribute
 * that is not `undefined` (`null` clears it) and never the read-only
 * credentials. Values are masked by `util.inspect` and `JSON.stringify` on
 * the objects the builders and the API return; a spread copy is not masked.
 */
export type SmsTrunkConfiguration =
  | SmsToEmailConfiguration
  | SmsHttpInConfiguration
  | SmsHttpOutConfiguration
  | SmsSmppEsmeConfiguration
  | SmsSmppSmscConfiguration
  | GenericSmsTrunkConfiguration;

type KnownSmsTrunkConfiguration = Exclude<SmsTrunkConfiguration, GenericSmsTrunkConfiguration>;
type KnownType = KnownSmsTrunkConfiguration['type'];

// Wire key of each attribute, per type; keys are never derived with camel()/snake()
// because the values of some of them are user dictionaries.
const WIRE_KEYS: Record<KnownType, Record<string, string>> = {
  sms_to_email: { sendTo: 'send_to', subject: 'subject', message: 'message' },
  http_in: {
    url: 'url',
    httpMethod: 'http_method',
    queryParameters: 'query_parameters',
    headers: 'headers',
    bodyType: 'body_type',
    body: 'body',
    followRedirect: 'follow_redirect',
    validateHttpsCertificate: 'validate_https_certificate',
  },
  http_out: {
    callbackUrl: 'callback_url',
    allowedIps: 'allowed_ips',
    authName: 'auth_name',
    authPassword: 'auth_password',
  },
  smpp_esme: {
    systemType: 'system_type',
    allowedIps: 'allowed_ips',
    serverLocation: 'server_location',
    systemId: 'system_id',
    password: 'password',
  },
  smpp_smsc: {
    host: 'host',
    txPort: 'tx_port',
    rxPort: 'rx_port',
    transceiverMode: 'transceiver_mode',
    connectionTimeout: 'connection_timeout',
    useSsl: 'use_ssl',
    systemId: 'system_id',
    systemType: 'system_type',
    password: 'password',
    serverLocation: 'server_location',
  },
};

const READ_ONLY_KEYS: Record<KnownType, readonly string[]> = {
  sms_to_email: [],
  http_in: [],
  http_out: ['authName', 'authPassword'],
  smpp_esme: ['systemId', 'password'],
  smpp_smsc: [],
};

export const SMS_HTTP_IN_SENSITIVE_KEYS = ['headers'] as const;
export const SMS_HTTP_OUT_SENSITIVE_KEYS = ['authName', 'authPassword'] as const;
export const SMS_SMPP_ESME_SENSITIVE_KEYS = ['systemId', 'password'] as const;
export const SMS_SMPP_SMSC_SENSITIVE_KEYS = ['password'] as const;

const SENSITIVE_KEYS: Record<KnownType, readonly string[]> = {
  sms_to_email: [],
  http_in: SMS_HTTP_IN_SENSITIVE_KEYS,
  http_out: SMS_HTTP_OUT_SENSITIVE_KEYS,
  smpp_esme: SMS_SMPP_ESME_SENSITIVE_KEYS,
  smpp_smsc: SMS_SMPP_SMSC_SENSITIVE_KEYS,
};

function isKnownType(type: unknown): type is KnownType {
  return typeof type === 'string' && Object.prototype.hasOwnProperty.call(WIRE_KEYS, type);
}

export function isGenericSmsTrunkConfiguration(c: SmsTrunkConfiguration): c is GenericSmsTrunkConfiguration {
  return 'attributes' in c;
}

export function isSmsToEmail(c: SmsTrunkConfiguration): c is SmsToEmailConfiguration {
  return !('attributes' in c) && c.type === 'sms_to_email';
}

export function isSmsHttpIn(c: SmsTrunkConfiguration): c is SmsHttpInConfiguration {
  return !('attributes' in c) && c.type === 'http_in';
}

export function isSmsHttpOut(c: SmsTrunkConfiguration): c is SmsHttpOutConfiguration {
  return !('attributes' in c) && c.type === 'http_out';
}

export function isSmsSmppEsme(c: SmsTrunkConfiguration): c is SmsSmppEsmeConfiguration {
  return !('attributes' in c) && c.type === 'smpp_esme';
}

export function isSmsSmppSmsc(c: SmsTrunkConfiguration): c is SmsSmppSmscConfiguration {
  return !('attributes' in c) && c.type === 'smpp_smsc';
}

/**
 * Returns a copy of the configuration with its secrets replaced by
 * `'[FILTERED]'`: `headers` (http_in), the credentials (http_out, smpp_esme),
 * `password` (smpp_smsc) and every non-null attribute of a generic
 * configuration. Use it before logging. The original object is unchanged.
 */
export function redactSmsTrunkConfiguration<T extends SmsTrunkConfiguration>(config: T): T {
  if (isGenericSmsTrunkConfiguration(config)) {
    const attributes: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(config.attributes ?? {})) {
      attributes[key] = value == null ? value : '[FILTERED]';
    }
    return { ...config, attributes } as T;
  }
  const keys = isKnownType(config.type) ? SENSITIVE_KEYS[config.type] : [];
  return redactSensitiveKeys(config, keys as ReadonlyArray<keyof T>);
}

const NODE_INSPECT_CUSTOM = Symbol.for('nodejs.util.inspect.custom');

// Non-enumerable, so the hooks never reach the wire, a snapshot or a spread copy.
function installRedaction<T extends SmsTrunkConfiguration>(config: T): T {
  const redacted = () => redactSmsTrunkConfiguration(config);
  Object.defineProperty(config, NODE_INSPECT_CUSTOM, { value: redacted, enumerable: false, writable: false });
  Object.defineProperty(config, 'toJSON', { value: redacted, enumerable: false, writable: false });
  return config;
}

export type SmsToEmailConfigurationInput = Omit<SmsToEmailConfiguration, 'type'>;
export type SmsHttpInConfigurationInput = Omit<SmsHttpInConfiguration, 'type'>;
export type SmsHttpOutConfigurationInput = Omit<SmsHttpOutConfiguration, 'type' | 'authName' | 'authPassword'>;
export type SmsSmppEsmeConfigurationInput = Omit<SmsSmppEsmeConfiguration, 'type' | 'systemId' | 'password'>;
export type SmsSmppSmscConfigurationInput = Omit<SmsSmppSmscConfiguration, 'type'>;

export function smsToEmailConfiguration(attrs: SmsToEmailConfigurationInput): SmsToEmailConfiguration {
  return installRedaction({ type: 'sms_to_email', ...attrs });
}

export function smsHttpInConfiguration(attrs: SmsHttpInConfigurationInput): SmsHttpInConfiguration {
  return installRedaction({ type: 'http_in', ...attrs });
}

export function smsHttpOutConfiguration(attrs: SmsHttpOutConfigurationInput): SmsHttpOutConfiguration {
  return installRedaction({ type: 'http_out', ...attrs });
}

export function smsSmppEsmeConfiguration(attrs: SmsSmppEsmeConfigurationInput): SmsSmppEsmeConfiguration {
  return installRedaction({ type: 'smpp_esme', ...attrs });
}

export function smsSmppSmscConfiguration(attrs: SmsSmppSmscConfigurationInput): SmsSmppSmscConfiguration {
  return installRedaction({ type: 'smpp_smsc', ...attrs });
}

/** A configuration sent exactly as written (see {@link GenericSmsTrunkConfiguration}). */
export function genericSmsTrunkConfiguration(
  type: string,
  attributes: Record<string, unknown> = {},
): GenericSmsTrunkConfiguration {
  return installRedaction({ type, attributes });
}

interface SerializedSmsTrunkConfiguration {
  type: string;
  attributes: Record<string, unknown>;
}

/** Builds the wire form; the caller's object is never modified or referenced. */
export function serializeSmsTrunkConfiguration(config: SmsTrunkConfiguration): SerializedSmsTrunkConfiguration {
  if (isGenericSmsTrunkConfiguration(config)) {
    return { type: config.type, attributes: cloneJson(config.attributes ?? {}) };
  }
  const type = config.type as unknown;
  if (!isKnownType(type)) {
    throw new DidwwClientError(
      `Unknown SMS trunk configuration type "${String(type)}": use genericSmsTrunkConfiguration(type, attributes)`,
    );
  }
  const source = config as unknown as Record<string, unknown>;
  const readOnly = READ_ONLY_KEYS[type];
  const attributes: Record<string, unknown> = {};
  for (const [key, wireKey] of Object.entries(WIRE_KEYS[type])) {
    if (readOnly.includes(key)) continue;
    const value = source[key];
    if (value !== undefined) attributes[wireKey] = cloneJson(value);
  }
  return { type, attributes };
}

/** Reads the wire form `{type, attributes}`; the result never shares objects with the input. */
export function deserializeSmsTrunkConfiguration(data: Record<string, unknown>): SmsTrunkConfiguration {
  const type = data.type as string;
  const attributes = isPlainObject(data.attributes) ? data.attributes : {};
  if (!isKnownType(type)) {
    return installRedaction({ type, attributes: cloneJson(attributes) });
  }
  const camelKeys = new Map(Object.entries(WIRE_KEYS[type]).map(([key, wireKey]) => [wireKey, key]));
  const config: Record<string, unknown> = { type };
  for (const [wireKey, value] of Object.entries(attributes)) {
    const key = camelKeys.get(wireKey) ?? camel(wireKey);
    if (key !== '__proto__') config[key] = normalizeNumbers(value);
  }
  return installRedaction(config as unknown as KnownSmsTrunkConfiguration);
}
